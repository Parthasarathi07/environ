"""
build_docs.py — regenerates the written memo, the slide deck and the interview
pack straight from the analysis.

Why generated instead of typed: the numbers in a portfolio write-up go stale
the moment you re-run the analysis. Here they cannot. One command after any
data change:

    .venv/bin/python -m environ.scripts.build_docs

outputs
    environ/docs/memo.md          the 2-page written case
    environ/docs/memo.html        same, styled, printable, self-contained
    environ/docs/deck.html        12 slides, arrow-key navigation, print to PDF
    environ/docs/interview-pack.md  resume bullets, 90s script, Q&A bank
    environ/docs/transcript.md    full spoken version of the deck

PNG exhibits are written separately by environ.scripts.make_figures.
"""

