# ---------------------------------------------------------------------------
def load(panel: str, firms: str) -> dict:
    p = S.load_panel(panel)
    f = pd.read_csv(firms) if os.path.exists(firms) else None
    out = S.analyse(p, f)
    out["provenance"] = {
        "source": p.source,
        "is_synthetic": p.source.startswith("demo"),
        "generator": "environ/data/generate_data.py",
    }
    return out


class Doc:
    """Formatting helpers shared by every generated document."""

    def __init__(self, o: dict):
        self.o = o
        u = o["universe"]
        na, ne = o["sorts"]["naive"], o["sorts"]["sector_neutral"]
        risk = o["risk"]
        reg = {s["id"]: s for s in o["regressions"]["specs"]}
        self.u = u
        self.na, self.ne = na, ne
        self.risk, self.reg = risk, reg
        self.a = o["attribution"]
        self.v = o["verdict"]["answers"]
        self.level = next(c for c in reg["sector_neutral"]["result"]["coef"] if c["name"] == "z_neu")
        self.mom = next(c for c in reg["sector_neutral"]["result"]["coef"] if c["name"] == "m_neu")
        self.riskcoef = next(c for c in reg["risk"]["result"]["coef"] if c["name"] == "z_neu")
        self.span = f"{u['span'][0][:7]} to {u['span'][1][:7]}"
        self.demo = u["source"].startswith("demo")
        self.yn = f"{u['n_firms']} firms / {u['n_months']} months"

    # text bits reused verbatim across documents so they can never disagree
    @property
    def headline(self) -> str:
        return (
            f"The naive ESG quintile spread is {self.ne['spread_ret_ann_pct']:+.1f}%/yr once you compare firms "
            f"with their own sector (t={self.ne['spread_t']:+.1f}); as published it is "
            f"{self.na['spread_ret_ann_pct']:+.1f}%/yr (t={self.na['spread_t']:+.1f})."
        )

    @property
    def risk_line(self) -> str:
        """Used by both the memo and the deck so the two can never disagree."""
        r = self.risk["rows"]
        return (
            f"annualised vol {r[0]['vol_ann_pct']:.1f}% → {r[4]['vol_ann_pct']:.1f}%, "
            f"downside capture {r[0]['downside_capture_pct']:.0f}% → {r[4]['downside_capture_pct']:.0f}%, "
            f"worst drawdown {r[0]['max_drawdown_pct']:.1f}% → {r[4]['max_drawdown_pct']:.1f}%"
        )

    @property
    def source_note(self) -> str:
        if not self.demo:
            return f"Source: {self.u['source']}. {self.yn}, {self.span}."
        return (
            f"Source: **demo panel — synthetic**, generated by `environ/data/generate_data.py` from the named "
            f"assumptions in `environ/config.py` ({self.yn}, {self.span}). "
            "No MSCI licence or price feed was used. Every figure regenerates from real data via `/api/upload`."
        )


