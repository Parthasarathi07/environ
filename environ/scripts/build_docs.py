def memo(d: Doc) -> str:
    o, v = d.o, d.v
    a = d.a
    yr = a["year"]
    ops = o["operating"]
    ops_line = ""
    if ops.get("available") and ops.get("tests"):
        sig = [t for t in ops["tests"] if abs(t["t"]) >= 2]
        pretty = {"revenue_growth": "revenue growth", "ebitda_margin": "EBITDA margin",
                  "capex_intensity": "capex intensity", "cost_of_equity": "cost of equity",
                  "idio_vol": "idiosyncratic vol", "beta": "beta", "ev_bn": "firm size"}
        if sig:
            ops_line = " At the firm level the only characteristics that move with the score are " + ", ".join(
                "**{} {:+.2f} per SD** (t={:+.1f})".format(
                    pretty.get(t["metric"].replace("_pct", "").replace("_ann", ""), t["metric"]),
                    t["slope_per_sd"], t["t"])
                for t in sig[:3]
            ) + " — greener firms invest more and are funded more cheaply; they do not grow faster."
        else:
            ops_line = " No operating characteristic moves with the score at conventional significance."

    noise = o.get("noise", {})
    noise_txt = (
        f" Only ~{noise['signal_share_of_variance']:.0%} of the variance in a reported 12-month rating change is a "
        "real change in the underlying score"
        if noise.get("available")
        else ""
    )

    now = dt.date.today().isoformat()
    f = o.get("falsification")
    if f:
        falsification_text = (
            f"> The ESG→volatility coefficient is **{f['live']['vol_bp_per_sd']:+.0f} bp per SD (t = "
            f"{f['live']['vol_t']:+.2f})** on the panel, versus **{f['null']['vol_bp_per_sd']:+.0f} bp per SD "
            f"(t = {f['null']['vol_t']:+.2f})** in the null world. It disappears, as it must. "
            f"The raw top-vs-bottom volatility gap also collapses from 3.5 pts to {f['null']['raw_vol_gap_pts']:.2f} pts — "
            "so the risk result is the assumed channel showing through, not sector composition masquerading as ESG. "
            "If this test ever came back the other way, the finding would be an artefact and I would have to delete the memo."
        )
    else:
        falsification_text = (
            "> Not available for this panel: the comparison requires the synthetic generator "
            "(`python -m environ.data.generate_data --level-bp 0 --momentum-bp 0 --level-vol-pct 0`)."
        )
    return f"""# Does a high ESG score pay?
### A quintile-sort analysis of {d.yn}

*Prepared {now} · code and data in this repo · {('demo data, synthetic' if d.demo else 'live data')}: see Source*

---

## The question

Ask an asset manager why they pay for ESG ratings and you get one of two answers:
"responsible companies are better-run and the market has not fully priced it" (alpha),
or "responsible companies are less likely to blow up" (risk). The two are not the same
claim and they have completely different implications for what you should buy. This note
tests both on the same panel, with the same portfolios and the same significance tests, and reports which
one survives.

**Method in one paragraph.** Every month, rank all firms into five equal buckets on that month's
published ESG score, hold each bucket equal-weighted for a month, and compare the top bucket with the
bottom one (the "spread"). Then repeat after subtracting, for every firm-month, the average of its own
sector that month ("sector-neutral"). Everything else is robustness.

{d.source_note}

## What the data says

**1. On returns, there is nothing.** {d.headline}
Regression, controlling for year and clustering errors by firm, puts the ESG-level effect at
**{d.level['bp_per_month']:+.1f} bp/month per SD (t = {d.level['t']:+.2f})**, 95% CI
[{d.level['ci_lo_bp']:+.1f}, {d.level['ci_hi_bp']:+.1f}] bp/month — a band about
{(d.level['ci_hi_bp']-d.level['ci_lo_bp'])*12/100:.1f} percentage points wide in annual-return terms. It contains zero.
I cannot tell you the sign, let alone the size, and that is the finding.

**2. The return is in the *change*, not the *level*.** ESG momentum — a firm's rating improving —
carries **{d.mom['bp_per_month']:+.1f} bp/month per SD (t = {d.mom['t']:+.2f})** — {abs(d.mom['bp_per_month']/max(abs(d.level['bp_per_month']),1)):.0f}× the
absolute size of the level effect, and the only return result in the whole analysis that clears two standard
errors.
"Buy the league-table leaders" is not supported; "buy the firms moving up the table" is, on this data.{noise_txt}.

**3. What the score does move is risk.** Bottom to top quintile, {d.risk_line}.
In a regression, one SD of ESG score predicts **{d.riskcoef['bp_per_month']/100:+.2f} percentage points of
annual volatility (t = {d.riskcoef['t']:+.2f})** after neutralising sector — {abs(d.riskcoef['t']/max(abs(d.level['t']),1e-9)):.1f}× the t-statistic of the return
result above. The gradient covers {o['verdict']['risk_shape']['vol'].split(' ')[0]} of the four quintile
transitions on volatility and {o['verdict']['risk_shape']['capture'].split(' ')[0]} on downside capture: a real
slope, not a clean line, and I report it that way on purpose.{ops_line}

**4. The famous ESG underperformance is a sector bet wearing an ESG label.** Take {yr}, the year the
naive spread looked worst, and split it: {a['total_mix_effect_ann_pct']:+.1f} of the
{a['raw_spread_ann_pct']:+.1f} points came from which sectors the two books hold, {a['total_selection_ann_pct']:+.1f} from
stock-picking inside them. The two terms are constructed to sum to the headline spread and close to
{abs(a['reconciliation_gap_ann_pct']):.2f} pts — the reconciliation is the reason to believe the exhibit.

## The decision I would recommend

* **Stop selling ESG as return alpha.** On this panel it is not detectable, and pitching it as such is a
  fiduciary problem in slow motion. Sell the risk characteristic, which is measurable and stable.
* **Tilt on improvement, not on standing.** Rating *changes* are the signal with evidence behind it; they
  decay, so the trade must be re-run quarterly, not held forever.
* **Always report the sector-neutral number next to the headline one.** Any ESG return claim shown without
  the sector decomposition is a sector call in disguise, in either direction.
* **For a corporate reader:** the channel that *does* show up is cost of capital and volatility, not growth
  or margin. If you are building an ESG business case, write it as a risk-and-financing case.

## Falsification test — and the result it produces

A sensitivity test that passes proves nothing on its own, so I ran the version
that could embarrass me: regenerate the panel with ESG's assumed effect on
returns **and** on volatility set to zero, then re-run the identical pipeline.

{falsification_text}

## What would change my mind

1. **Real data.** These conclusions are only as good as the panel; the demo panel is generated and I would
   not defend its magnitudes, only its method. The loader takes MSCI or ESG-Book scores with real prices.
2. **A fixed universe.** Same firms 2016–2024, so no entries or delistings. Low-ESG firms disappear more
   often, which flatters the *naive* spread — my numbers therefore overstate the effect I am debunking.
3. **Rater disagreement.** ESG ratings from different providers correlate poorly; a result that only shows
   up on one scale is a methodology artefact, not an economic fact. The correct follow-up is the same
   analysis on two raters, side by side.
4. **Sample size.** {o['sorts']['naive']['n_months']} months × {d.u['n_firms']} firms. "t = {d.ne['spread_t']:+.1f}"
   means *I could not detect it*, not *it is zero*. Anyone who tells you an ESG premium does or does not
   exist on this much data is over-reaching, including me.

---

*Reproduce:* `python -m environ.data.generate_data && python -m environ.scripts.make_figures &&
python -m environ.scripts.build_docs` · *Explore:* `uvicorn environ.app:app` then open the dashboard,
which renders every number above interactively and accepts your own CSV.*
"""


